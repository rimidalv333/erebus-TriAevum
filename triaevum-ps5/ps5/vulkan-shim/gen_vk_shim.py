#!/usr/bin/env python3
"""Generate a Vulkan "loader" for the PS5: every core entry point forwards to RADV.

The console has no Vulkan loader; RADV is linked into the title and exports one
function, vk_icdGetInstanceProcAddr. TriAevum's renderer calls the Vulkan
functions by name, so this generates a definition of each one that finds RADV's
entry point on first use and calls it.

usage: gen_vk_shim.py VULKAN_CORE_H OUTPUT_C
"""
import re
import sys

header = open(sys.argv[1], encoding="utf-8").read()

# Platform and beta sections are not part of the console's Vulkan
header = re.sub(r"#ifdef VK_ENABLE_BETA_EXTENSIONS.*?#endif /\* VK_ENABLE_BETA_EXTENSIONS \*/", "", header, flags=re.S)
header = re.sub(r"#ifdef VK_USE_PLATFORM_\w+.*?#endif", "", header, flags=re.S)

proto = re.compile(r"VKAPI_ATTR\s+([A-Za-z0-9_ \*]+?)\s+VKAPI_CALL\s+(vk\w+)\(([^;]*?)\);", re.S)


def split_params(text):
    out, depth, cur = [], 0, ""
    for ch in text:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


GLOBAL = {"vkCreateInstance", "vkEnumerateInstanceExtensionProperties",
          "vkEnumerateInstanceLayerProperties", "vkEnumerateInstanceVersion"}
SPECIAL = {"vkGetInstanceProcAddr"}
seen = set()
body = []
for m in proto.finditer(header):
    ret, name, params = m.group(1).strip(), m.group(2), re.sub(r"\s+", " ", m.group(3)).strip()
    if name in seen or name in SPECIAL:
        continue
    seen.add(name)
    plist = [] if params == "void" else split_params(params)
    names = []
    for p in plist:
        p = re.sub(r"\[[^\]]*\]", "", p).strip()
        names.append(re.findall(r"[A-Za-z_][A-Za-z0-9_]*", p)[-1])
    call = ", ".join(names)
    inst = "NULL" if name in GLOBAL else "g_instance"
    fn = f"PFN_{name}"
    lines = [f"VKAPI_ATTR {ret} VKAPI_CALL {name}({params}) {{",
             f"    static {fn} fn;",
             f"    if (!fn) fn = ({fn})vk_icdGetInstanceProcAddr({inst}, \"{name}\");"]
    if name == "vkCreateInstance":
        lines += ["    VkResult result = fn(pCreateInfo, pAllocator, pInstance);",
                  "    if (result == VK_SUCCESS) g_instance = *pInstance;",
                  "    return result;"]
    elif ret == "void":
        lines += [f"    fn({call});"]
    else:
        lines += [f"    return fn({call});"]
    lines.append("}")
    body.append("\n".join(lines))

out = f"""/* Generated by gen_vk_shim.py from vulkan_core.h - do not edit.
 * The PS5 has no Vulkan loader: these forward each Vulkan call to RADV, which is
 * linked into the title and exports only vk_icdGetInstanceProcAddr. */
#include <vulkan/vulkan.h>

extern PFN_vkVoidFunction vk_icdGetInstanceProcAddr(VkInstance instance, const char *name);

static VkInstance g_instance;

VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vkGetInstanceProcAddr(VkInstance instance, const char *name) {{
    return vk_icdGetInstanceProcAddr(instance, name);
}}

{chr(10).join(body)}
"""
open(sys.argv[2], "w", encoding="utf-8").write(out)
print(f"{len(body)} Vulkan functions", file=sys.stderr)
