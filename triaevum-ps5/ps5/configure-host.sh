#!/bin/sh
# usage: configure-host.sh SRC BUILD   (needs PS5_KIT PS5_DEPS_PREFIX WORK_DEPS as absolute paths)
set -e
SRC=$1; BUILD=$2
exec cmake -S "$SRC" -B "$BUILD" -G Ninja -DCMAKE_TOOLCHAIN_FILE="$(cd "$(dirname "$0")" && pwd)/toolchain.cmake" \
 -DPS5_KIT="$PS5_KIT" -DPS5_DEPS_PREFIX="$PS5_DEPS_PREFIX" -DCMAKE_BUILD_TYPE=Release \
 -DOOT3D_ENABLE_VULKAN_RENDERER=ON -DTHREE_DS_RECOMP_ENABLE_VULKAN=ON -DTHREE_DS_RECOMP_ENABLE_NRI=OFF \
 -DTHREE_DS_RECOMP_ENABLE_SSSR=OFF -DTHREE_DS_RECOMP_ENABLE_CACAO=OFF -DTHREE_DS_RECOMP_ENABLE_IMMERSE=OFF \
 -DTHREE_DS_RECOMP_ENABLE_DLSS_MODULE=OFF -DTHREE_DS_RECOMP_ENABLE_NRI_UPSCALER_SDKS=OFF \
 -DOOT3D_DIRECT_AOT_PLUGIN=ON -DOOT3D_WHOLE_AOT_PRODUCT_MODE=ON \
 -DVulkan_INCLUDE_DIR="$WORK_DEPS/Vulkan-Headers/include" -DVulkan_LIBRARY="$PS5_DEPS_PREFIX/lib/libvulkan_shim.a" \
 -DSDL2_DIR="$PS5_DEPS_PREFIX/lib/cmake/SDL2" -DTHREE_DS_RECOMP_SHADERC_INCLUDE_DIR="$PS5_DEPS_PREFIX/include" \
 -DCMAKE_TLS_CAINFO=/root/.ccr/ca-bundle.crt \
 -DCMAKE_PROJECT_INCLUDE="$(cd "$(dirname "$0")" && pwd)/project-include.cmake" -DTRIAEVUM_LICENSE_FILE="$SRC/LICENSE" \
 ${TRIAEVUM_PS5_TITLE_DIR:+-DTRIAEVUM_PS5_TITLE_DIR="$TRIAEVUM_PS5_TITLE_DIR"}
